import assert from 'node:assert/strict';
import { DEFAULT_EXCHANGE_PAIR, EXCHANGE_CURRENCIES, fetchExchangeQuote, parseExchangeAmount, simulateExchange, validateQuote } from '../bravus-bank-frontend/src/lib/exchangeQuotes.js';
const now = Date.parse('2026-09-09T12:00:00Z');
const data = { base: 'USD', quote: 'BRL', rate: 5.12345, date: '2026-09-08' };
const quote = validateQuote(data, 'USD', 'BRL', now);
assert.deepEqual(DEFAULT_EXCHANGE_PAIR, { base: 'USD', quote: 'BRL' });
assert.ok(EXCHANGE_CURRENCIES.length >= 30);
assert.equal(parseExchangeAmount('1.234,56'), 123456n);
assert.equal(parseExchangeAmount('1234.56'), 123456n);
for (const amount of ['', '0', '-1', 'NaN', 'Infinity', '1e3', '1,234.56', '1.2.3', '1,234', '99999999999999']) assert.throws(() => parseExchangeAmount(amount));
assert.equal(simulateExchange('100', quote, now).targetMinor, '51235');
assert.equal(simulateExchange('0,01', { ...quote, rate: '1.5' }, now).targetMinor, '2');
assert.equal(simulateExchange('100', { ...quote, quote: 'JPY', rate: '150.125' }, now).targetMinor, '15013');
assert.equal(simulateExchange('100', { ...quote, quote: 'KRW', rate: '1300' }, now).targetMinor, '130000');
assert.equal(simulateExchange('999999999999.99', { ...quote, rate: '1' }, now).targetMinor, '99999999999999');
for (const bad of [0, -1, NaN, Infinity, '5.1']) assert.throws(() => validateQuote({ ...data, rate: bad }, 'USD', 'BRL', now));
for (const date of ['2026-08-01', '2026-13-01', '2026-02-30', '2026-12-01', 'bad']) assert.throws(() => validateQuote({ ...data, date }, 'USD', 'BRL', now));
assert.throws(() => validateQuote({ ...data, quote: 'EUR' }, 'USD', 'BRL', now));
assert.throws(() => simulateExchange('1', quote, now + 9 * 86400000));
let requests = [];
const fetchImpl = async (url, options) => { requests.push({ url, options }); return { ok: true, json: async () => data }; };
await fetchExchangeQuote('USD', 'BRL', { now, fetchImpl });
assert.equal(requests.length, 1);
assert.equal(requests[0].url, 'https://api.frankfurter.dev/v2/rate/USD/BRL?providers=ECB');
assert.equal(requests[0].options.credentials, 'omit');
assert.equal(requests[0].options.method, 'GET');
assert.equal(requests[0].options.body, undefined);
assert.equal(requests[0].options.headers, undefined);
const same = await fetchExchangeQuote('USD', 'USD', { now, fetchImpl });
assert.equal(same.rate, '1');
assert.equal(requests.length, 1);
assert.equal(simulateExchange('10', same, now).targetMinor, '1000');
await assert.rejects(fetchExchangeQuote('FAKE', 'BRL', { now, fetchImpl }));
await assert.rejects(fetchExchangeQuote('USD', 'BRL', { now, fetchImpl: async () => ({ ok: false }) }));
await assert.rejects(fetchExchangeQuote('USD', 'BRL', { now, fetchImpl: async () => { throw new TypeError('network'); } }), /conexão/);
const abortingFetch = (_url, { signal }) => new Promise((_resolve, reject) => { const stop = () => reject(new DOMException('Aborted', 'AbortError')); if (signal.aborted) stop(); else signal.addEventListener('abort', stop, { once: true }); });
await assert.rejects(fetchExchangeQuote('USD', 'BRL', { now, timeoutMs: 5, fetchImpl: abortingFetch }), /demorou/);
const controller = new AbortController();
const pending = fetchExchangeQuote('USD', 'BRL', { now, signal: controller.signal, fetchImpl: abortingFetch });
controller.abort();
await assert.rejects(pending, { name: 'AbortError' });
console.log('exchange: real-source contract, USD default, 30 currencies, exact rounding, JPY/KRW, stale/error/timeout/cancel, no account data sent: passed');
